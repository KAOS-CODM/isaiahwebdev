#!/usr/bin/env node
/**
 * generate-static-projects.mjs
 * Generate the crawlable project markup that ships in the initial HTML of
 * projects.html and index.html.
 *
 * Source of truth
 * ---------------
 * The production projects API is the only default source. The committed
 * /data/projects.json fallback is deliberately NOT used here: it currently
 * contains records that are not published by the CMS, and treating it as
 * authoritative would publish stale or contradictory projects. If the API is
 * unavailable, returns an unusable shape, or yields zero usable projects, the
 * generator fails closed and leaves every file untouched.
 *
 * Consistency with the browser
 * ----------------------------
 * Normalization, ordering, published/featured selection and detail URLs all
 * come from js/projects-schema.js. Card markup comes from js/project-card.js
 * and the homepage markup from js/project.js - the same functions the browser
 * uses to hydrate. A successful generation therefore produces markup that the
 * live hydration path agrees with when it loads the same dataset.
 *
 * Usage
 * -----
 *   node scripts/generate-static-projects.mjs
 *   node scripts/generate-static-projects.mjs --check
 *   node scripts/generate-static-projects.mjs --input tests/fixtures/production-projects-api.json
 *
 * See docs/static-project-generation.md for the operating procedure and the
 * remaining freshness dependency.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  normalizeProjects,
  projectPagePath,
  publishedProjects,
} from '../js/projects-schema.js';
import { renderProjectCard } from '../js/project-card.js';
import { buildHomepageWork } from '../js/project.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const SITE_ORIGIN = 'https://isaiahwebdev.onrender.com';
export const PROJECTS_API_URL =
  'https://isaiahwebdev-api.onrender.com/api/content/projects';

export const GENERATED_COMMENT =
  '<!-- Generated by scripts/generate-static-projects.mjs from the production projects API. Do not edit by hand. -->';

export const NO_PROJECTS_MARKUP =
  '<p class="no-projects">No projects available at the moment.</p>';

export const MARKERS = Object.freeze({
  listing: ['<!-- static-projects:start -->', '<!-- static-projects:end -->'],
  homepage: ['<!-- static-featured:start -->', '<!-- static-featured:end -->'],
  schema: ['<!-- static-projects-schema:start -->', '<!-- static-projects-schema:end -->'],
});

export const FILES = Object.freeze({
  listing: 'projects.html',
  homepage: 'index.html',
  schema: 'projects.html',
});

/**
 * Render the initial listing markup. Only published projects are included, in
 * the shared schema's order.
 * @param {object[]} projects - Projects normalized by js/projects-schema.js.
 * @returns {string}
 */
export function renderProjectListMarkup(projects) {
  const published = publishedProjects(projects);
  if (published.length === 0) return NO_PROJECTS_MARKUP;
  return published.map(renderProjectCard).join('');
}

/**
 * Render the initial homepage "Selected Work" markup. Only projects explicitly
 * flagged `featured === true` (and published) are included by the shared
 * homepage selector.
 * @param {object[]} projects - Projects normalized by js/projects-schema.js.
 * @returns {string}
 */
export function renderHomepageMarkup(projects) {
  const { featured, html } = buildHomepageWork(projects);
  return featured ? html.trim() : NO_PROJECTS_MARKUP;
}

function absoluteUrl(origin, value) {
  const src = typeof value === 'string' ? value.trim() : '';
  if (!src) return '';
  if (/^https?:\/\//i.test(src)) return src;
  return `${origin}/${src.replace(/^\/+/, '')}`;
}

function safeJsonLd(value) {
  // Escape `<` so project text can never terminate the script element.
  return JSON.stringify(value, null, 4).replace(/</g, '\\u003c');
}

/**
 * Build an ItemList that describes exactly the published projects rendered in
 * the listing. Each item points at the on-site detail route and includes only
 * the CMS description and image; unverified external project links are omitted.
 *
 * @param {object[]} projects - Projects normalized by js/projects-schema.js.
 * @param {string} [origin]
 * @returns {string} A complete JSON-LD script element, or '' when empty.
 */
export function renderProjectsStructuredData(projects, origin = SITE_ORIGIN) {
  const site = String(origin || SITE_ORIGIN).replace(/\/+$/, '');
  const published = publishedProjects(projects);
  if (published.length === 0) return '';

  const itemListElement = published.map((project, index) => {
    const item = {
      '@type': 'SoftwareApplication',
      name: project.title,
      url: `${site}${projectPagePath(project.slug)}`,
      applicationCategory: 'WebApplication',
      operatingSystem: 'Web',
      author: { '@id': `${site}/#isaiah-adelowo` },
    };

    const description = project.shortDescription || project.description || '';
    if (description) item.description = description;

    const image = absoluteUrl(site, project.images?.[0]?.src);
    if (image) item.image = image;

    // Deliberately no liveUrl/codeRepository: several CMS-supplied external
    // URLs are currently dead (404/503), and the listing schema should point
    // to the on-site detail page rather than republish unverified links.

    return {
      '@type': 'ListItem',
      position: index + 1,
      item,
    };
  });

  const data = {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    '@id': `${site}/projects#projects`,
    name: 'Web Development Projects by Isaiah Adelowo',
    description: 'Web applications and websites designed and built by Isaiah Adelowo.',
    numberOfItems: published.length,
    itemListElement,
  };

  return `<script type="application/ld+json">\n${safeJsonLd(data)}\n    </script>`;
}

/**
 * Replace the content between two unique marker comments, preserving the
 * file's existing line-ending convention.
 *
 * @param {string} source
 * @param {[string, string]} markers
 * @param {string} inner
 * @param {string} [label]
 * @returns {string}
 */
export function replaceRegion(source, markers, inner, label = 'file') {
  const [startMarker, endMarker] = markers;
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker);

  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${label}: missing or invalid static region markers`);
  }
  if (
    source.indexOf(startMarker, start + startMarker.length) !== -1 ||
    source.indexOf(endMarker, end + endMarker.length) !== -1
  ) {
    throw new Error(`${label}: static region markers must be unique`);
  }

  const eol = source.includes('\r\n') ? '\r\n' : '\n';
  const normalized =
    typeof inner === 'string' && inner !== ''
      ? inner.replace(/\r\n/g, '\n').split('\n').join(eol)
      : '';

  const before = source.slice(0, start + startMarker.length);
  const after = source.slice(end);

  return normalized
    ? `${before}${eol}${normalized}${eol}${after}`
    : `${before}${eol}${after}`;
}

/**
 * Build the exact expected contents of both HTML files.
 * @param {{ listingSource: string, homepageSource: string, projects: object[], origin?: string }} input
 * @returns {{ listing: string, homepage: string }}
 */
export function buildExpectedContent({
  listingSource,
  homepageSource,
  projects,
  origin = SITE_ORIGIN,
}) {
  const listingHtml = renderProjectListMarkup(projects);
  const homepageHtml = renderHomepageMarkup(projects);
  const schema = renderProjectsStructuredData(projects, origin);

  const listingInner = `${GENERATED_COMMENT}\n${listingHtml.trim()}`;
  const schemaInner = schema ? `${GENERATED_COMMENT}\n${schema.trim()}` : '';

  const listing = replaceRegion(
    replaceRegion(listingSource, MARKERS.listing, listingInner, FILES.listing),
    MARKERS.schema,
    schemaInner,
    FILES.listing
  );

  const homepage = replaceRegion(
    homepageSource,
    MARKERS.homepage,
    `${GENERATED_COMMENT}\n${homepageHtml.trim()}`,
    FILES.homepage
  );

  return { listing, homepage };
}

function extractProjects(payload) {
  if (Array.isArray(payload)) return payload;
  if (payload && Array.isArray(payload.projects)) return payload.projects;
  throw new Error('API_INVALID_SHAPE: expected an array or { projects: [] }');
}

async function loadPayload({ inputPath, apiUrl, fetchImpl }) {
  if (inputPath) {
    return JSON.parse(await readFile(inputPath, 'utf8'));
  }

  if (typeof fetchImpl !== 'function') {
    throw new Error('No fetch implementation available to read the production API');
  }

  const response = await fetchImpl(apiUrl, {
    headers: { Accept: 'application/json' },
    signal: AbortSignal.timeout(30000),
  });

  if (!response.ok) {
    throw new Error(`API_HTTP_${response.status}`);
  }

  const contentType = response.headers.get('content-type') || '';
  if (!contentType.includes('application/json')) {
    throw new Error('API_INVALID_CONTENT_TYPE');
  }

  return response.json();
}

/**
 * Load raw projects and normalize them. Fails closed when the source yields no
 * usable project, so an API outage cannot silently replace real markup with
 * the local fallback or an empty page.
 *
 * @param {{ inputPath?: string|null, apiUrl?: string, fetchImpl?: Function }} [options]
 * @returns {Promise<object[]>}
 */
export async function loadSourceProjects({
  inputPath = null,
  apiUrl = PROJECTS_API_URL,
  fetchImpl = globalThis.fetch,
} = {}) {
  const payload = await loadPayload({ inputPath, apiUrl, fetchImpl });
  const projects = normalizeProjects(extractProjects(payload));

  if (projects.length === 0) {
    throw new Error(
      'NO_USABLE_PROJECTS: refusing to generate static markup from an empty project source'
    );
  }

  return projects;
}

/**
 * Generate (or check) the static markup.
 *
 * @param {{ root?: string, inputPath?: string|null, apiUrl?: string, check?: boolean, fetchImpl?: Function }} [options]
 * @returns {Promise<{ ok: boolean, changed: string[], stale: string[] }>}
 */
export async function generate({
  root = ROOT,
  inputPath = null,
  apiUrl = PROJECTS_API_URL,
  check = false,
  fetchImpl = globalThis.fetch,
} = {}) {
  const listingPath = path.join(root, FILES.listing);
  const homepagePath = path.join(root, FILES.homepage);

  const [listingSource, homepageSource, projects] = await Promise.all([
    readFile(listingPath, 'utf8'),
    readFile(homepagePath, 'utf8'),
    loadSourceProjects({ inputPath, apiUrl, fetchImpl }),
  ]);

  const expected = buildExpectedContent({
    listingSource,
    homepageSource,
    projects,
  });

  const outputs = [
    { file: listingPath, content: expected.listing },
    { file: homepagePath, content: expected.homepage },
  ];

  const changed = outputs
    .filter((output) => output.content !== (output.file === listingPath ? listingSource : homepageSource))
    .map((output) => path.relative(root, output.file));

  if (check) {
    if (changed.length > 0) {
      console.error('Static project markup is stale. Run: node scripts/generate-static-projects.mjs');
      for (const file of changed) console.error(`  - ${file}`);
      return { ok: false, changed: [], stale: changed };
    }
    console.log('Static project markup is up to date.');
    return { ok: true, changed: [], stale: [] };
  }

  if (changed.length === 0) {
    console.log('Static project markup is already up to date.');
    return { ok: true, changed: [], stale: [] };
  }

  for (const output of outputs) {
    await writeFile(output.file, output.content, 'utf8');
  }

  console.log('Generated static project markup from the production projects API:');
  for (const file of changed) console.log(`  - ${file}`);
  return { ok: true, changed, stale: [] };
}

function usage() {
  return [
    'Usage: node scripts/generate-static-projects.mjs [options]',
    '',
    'Options:',
    '  --check              Verify committed markup matches the source without writing',
    '  --input <file>       Read a recorded API response instead of fetching (testing)',
    '  --help               Show this help',
    '',
    'Documentation: docs/static-project-generation.md',
  ].join('\n');
}

function parseArgs(argv) {
  const options = { check: false, inputPath: null };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--check') {
      options.check = true;
    } else if (arg === '--input') {
      const value = argv[index + 1];
      if (!value) throw new Error('--input requires a file path');
      options.inputPath = path.resolve(value);
      index += 1;
    } else if (arg.startsWith('--input=')) {
      options.inputPath = path.resolve(arg.slice('--input='.length));
    } else if (arg === '--help' || arg === '-h') {
      options.help = true;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  return options;
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    console.log(usage());
    return;
  }

  const result = await generate({
    inputPath: options.inputPath,
    check: options.check,
  });

  if (!result.ok) process.exitCode = 1;
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]).toLowerCase() : '';
const modulePath = path.resolve(fileURLToPath(import.meta.url)).toLowerCase();

if (invokedPath && invokedPath === modulePath) {
  main().catch((error) => {
    console.error(`Generate failed: ${error.message}`);
    process.exitCode = 1;
  });
}
